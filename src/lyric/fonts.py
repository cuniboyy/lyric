FONTS = {
    'block': BLOCK_LETTERS,
    'compact': COMPACT_LETTERS,
}


def register(name, rows):
    """Register a font; glyph rows are lists of equal-length strings."""
    FONTS[name] = rows
    return rows


def load(path):
    """Load custom fonts from JSON.

    Keys starting with an underscore are documentation (the example file uses
    ``_comment``/``_format``/``_usage``) and are ignored, as is anything that is
    not a per-character mapping.
    """
    try:
        data = json.loads(path.read_text())
    except FileNotFoundError:
        return {}
    except (OSError, ValueError) as error:
        logging.warning('Ignoring font file %s: %s', path, error)
        return {}
    if not isinstance(data, dict):
        return {}
    loaded = {}
    for name, rows in data.items():
        if name.startswith('_') or not isinstance(rows, dict):
            continue
        if rows and all(isinstance(v, list) for v in rows.values()):
            register(name, rows)
            loaded[name] = rows
    return loaded


def get(name='block'):
    """Get a font by name, defaulting to the block letters."""
    return FONTS.get(name, BLOCK_LETTERS)


def render_text(text, name='block'):
    """Render text with a font; unknown characters become spaces."""
    font = get(name)
    height = len(font.get('A', ['']))
    lines = ['' for _ in range(height)]
    for char in text.upper():
        rows = font.get(char, font.get(' ', [' ']))
        width = max(len(row) for row in rows) + 1
        for i in range(height):
            lines[i] += rows[i] + ' ' if i < len(rows) else ' ' * width
    return lines
